#!/usr/bin/env node
// Bottle accepts a Dockerfile path, but no target. Keep its build in sync with upstream.
import { readFileSync, writeFileSync } from 'node:fs';

const root = new URL('../', import.meta.url);
const upstream = readFileSync(new URL('Dockerfile', root), 'utf8');
const boundary = '# ---------------------------------------------------------------------------------------------\nFROM scratch AS runtime';
if (upstream.split(boundary).length !== 2) throw new Error('Cannot locate the upstream runtime stage');
const generated = `# Generated by node scripts/bottle-dockerfile.mjs; do not edit directly.\n${upstream.split(boundary)[0]}
# Cloud in a Bottle uses the same compiled sources and bundled database as Home Assistant.
FROM ha AS bottle
LABEL org.opencontainers.image.title="Kept for Cloud in a Bottle"
ENV KEPT_HA=0 KEPT_HA_TRUST_GROUPS=0
COPY --chmod=0755 docker/bottle/start /usr/local/bin/kept-bottle-start
COPY --chmod=0644 docker/bottle/env.mjs /usr/local/lib/kept-bottle/env.mjs
COPY docker/healthcheck.mjs /app/docker/healthcheck.mjs
HEALTHCHECK --interval=30s --timeout=5s --start-period=120s --retries=3 \\
  CMD ["node", "/app/docker/healthcheck.mjs"]
ENTRYPOINT ["/usr/local/bin/kept-bottle-start"]
`.replaceAll('ARG SOURCE=https://github.com/keptinventory/kept', 'ARG SOURCE=https://github.com/pocketIlmatto/kept/tree/cloud-in-a-bottle');
const output = new URL('Dockerfile.bottle', root);
if (process.argv.includes('--check')) {
  if (readFileSync(output, 'utf8') !== generated) {
    throw new Error('Dockerfile.bottle is stale; run node scripts/bottle-dockerfile.mjs');
  }
  console.log('Dockerfile.bottle matches the upstream build stages');
} else {
  writeFileSync(output, generated);
}
