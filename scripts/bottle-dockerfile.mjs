#!/usr/bin/env node
// Bottle accepts a Dockerfile path, but no target. Keep its build in sync with upstream.
import { readFileSync, writeFileSync } from 'node:fs';

const root = new URL('../', import.meta.url);
const upstream = readFileSync(new URL('Dockerfile', root), 'utf8');
const boundary =
  '# ---------------------------------------------------------------------------------------------\nFROM scratch AS runtime';
if (upstream.split(boundary).length !== 2)
  throw new Error('Cannot locate the upstream runtime stage');
// pnpm 11 may auto-install before running scripts. Keep that install on the
// mounted store rather than embedding another copy in a Podman build layer.
const buildStages = upstream
  .split(boundary)[0]
  .replace(
    'COPY apps/web/package.json /src/apps/web/',
    'COPY apps/web/package.json /src/apps/web/\nCOPY apps/docs/package.json /src/apps/docs/',
  )
  .replaceAll(
    '    CI=true',
    '    CI=true \\\n    npm_config_store_dir=/pnpm-store \\\n    npm_config_cache_dir=/pnpm-cache',
  )
  .replace(
    'RUN pnpm --filter @kept/shared build',
    'RUN --mount=type=cache,id=kept-pnpm-store,target=/pnpm-store \\\n    --mount=type=cache,id=kept-pnpm-cache,target=/pnpm-cache \\\n    pnpm --filter @kept/shared build',
  );
const generated =
  `${buildStages.replace('# syntax=docker/dockerfile:1', '# syntax=docker/dockerfile:1\n# Generated by node scripts/bottle-dockerfile.mjs; do not edit directly.')}
# Cloud in a Bottle uses the same compiled sources and bundled database as Home Assistant.
FROM ha AS bottle
LABEL org.opencontainers.image.title="Kept for Cloud in a Bottle"
ENV KEPT_HA=0 KEPT_HA_TRUST_GROUPS=0
# The HA image restricts /data itself; Bottle mounts a nested directory below it.
RUN chmod 0711 /data
COPY --chmod=0755 docker/bottle/start /usr/local/bin/kept-bottle-start
COPY --chmod=0644 docker/bottle/env.mjs /usr/local/lib/kept-bottle/env.mjs
COPY docker/healthcheck.mjs /app/docker/healthcheck.mjs
HEALTHCHECK --interval=30s --timeout=5s --start-period=120s --retries=3 \\
  CMD ["node", "/app/docker/healthcheck.mjs"]
ENTRYPOINT ["/usr/local/bin/kept-bottle-start"]
`.replaceAll(
    'ARG SOURCE=https://github.com/keptinventory/kept',
    'ARG SOURCE=https://github.com/pocketIlmatto/kept',
  );
const output = new URL('Dockerfile.bottle', root);
if (process.argv.includes('--check')) {
  if (readFileSync(output, 'utf8') !== generated) {
    throw new Error('Dockerfile.bottle is stale; run node scripts/bottle-dockerfile.mjs');
  }
  console.log('Dockerfile.bottle matches the upstream build stages');
} else {
  writeFileSync(output, generated);
}
